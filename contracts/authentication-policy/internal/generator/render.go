package generator

import (
	"fmt"

	"google.golang.org/protobuf/compiler/protogen"
)

func renderMap(plugin *protogen.Plugin, file *protogen.File, entries []policyEntry) {
	generated := plugin.NewGeneratedFile(outputPath, file.GoImportPath)
	generated.P("// Code generated by protoc-gen-authentication-policy. DO NOT EDIT.")
	generated.P()
	generated.P("package ", file.GoPackageName)
	generated.P()
	generated.P("// MethodAuthenticationPolicies maps canonical gRPC full method names to their authentication policy.")
	generated.P("var MethodAuthenticationPolicies = map[string]AuthenticationPolicy{")
	for _, entry := range entries {
		generated.P(fmt.Sprintf("%q", entry.fullMethod), ": AuthenticationPolicy_", entry.constantName, ",")
	}
	generated.P("}")
}
